"""Sampler contract; model state must include ALL mutable inference caches."""
from typing import Protocol, Any
import numpy as np


class Sampler(Protocol):
    def initialize(self, rng: np.random.Generator) -> Any: ...
    def advance(self, state: Any, step: int, total_steps: int,
                rng: np.random.Generator) -> Any: ...
    def predict(self, state: Any) -> Any: ...
    def clone(self, state: Any) -> Any: ...
